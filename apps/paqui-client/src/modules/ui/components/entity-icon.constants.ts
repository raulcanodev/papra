export function isEntityIconName(icon: string) {
  return icon.startsWith(ENTITY_ICON_PREFIX);
}

/** The UnoCSS class of a stored `icon:<name>` value, undefined for emojis and icons that are not in the curated list */
export function getEntityIconClass(icon: string | null | undefined) {
  if (!icon || !isEntityIconName(icon)) {
    return undefined;
  }

  return ENTITY_ICON_CLASSES.get(icon.slice(ENTITY_ICON_PREFIX.length));
}

export function getEntityIconColorClasses(color: string | null | undefined) {
  return ENTITY_ICON_COLOR_CLASSES[(ENTITY_ICON_COLORS as readonly string[]).includes(color ?? '') ? color as EntityIconColor : 'gray'];
}
